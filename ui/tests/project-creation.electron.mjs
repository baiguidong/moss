import assert from 'node:assert/strict';
import path from 'node:path';
import { app, BrowserWindow } from 'electron';
import { createServer } from 'vite';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
const uiRoot = path.resolve(import.meta.dirname, '..');
const temp = await mkdtemp(path.join(tmpdir(), 'moss-project-creation-ui-'));
app.setPath('userData', path.join(temp, 'profile'));
app.on('window-all-closed', () => {});
let server, window;
const timeout = setTimeout(() => { console.error('Project creation UI timed out'); app.exit(1); }, 60_000);
app.whenReady().then(async () => {
  try {
    server = await createServer({ root: uiRoot, configFile: path.join(uiRoot, 'vite.config.ts'), cacheDir: path.join(temp, 'vite'), server: { host: '127.0.0.1', port: 0, strictPort: false, hmr: false } });
    await server.listen();
    window = new BrowserWindow({ show: false, width: 1000, height: 1100, webPreferences: { backgroundThrottling: false } });
    const evaluate = code => window.webContents.executeJavaScript(code);
    const waitFor = async code => { for (let i = 0; i < 100; i++) { if (await evaluate(code)) return; await new Promise(resolve => setTimeout(resolve, 30)); } throw new Error(`UI condition failed: ${code}`); };
    const click = text => evaluate(`[...document.querySelectorAll('button')].find(b => b.textContent.trim() === ${JSON.stringify(text)}).click()`);
    await window.loadURL(`http://127.0.0.1:${server.httpServer.address().port}/tests/fixtures/project-creation.html`);
    await waitFor("document.body.textContent.includes('完整展示第五行指令')");
    assert.equal(await evaluate("document.querySelector('[data-project-icon]').dataset.projectIcon"), 'generated');
    const originalPaths = await evaluate("[...document.querySelectorAll('header [data-project-icon] path')].map(path => path.getAttribute('d'))");
    assert.equal(await evaluate("getComputedStyle(document.querySelector('section')).position"), 'static');
    assert.equal(await evaluate("document.querySelector('[data-project-instructions-preview]').clientHeight"), 178);
    await writeFile(path.join(tmpdir(), 'moss-project-creation-review.png'), (await window.webContents.capturePage()).toPNG());
    await click('修改方案');
    await waitFor("document.body.textContent.includes('保存并重新预览')");
    await click('修改');
    await evaluate("document.querySelector('[aria-label=\"使用知识图标\"]').click()");
    await waitFor("document.querySelector('[aria-label=\"使用知识图标\"]').getAttribute('aria-pressed') === 'true'");
    await evaluate("document.querySelector('[aria-label=\"使用 AI 生成图标\"]').click()");
    await evaluate("document.querySelector('[aria-label=\"蓝色图标\"]').click()");
    await waitFor("document.querySelector('header [data-project-icon]').dataset.iconColor === 'blue'");
    await evaluate('document.fonts.ready.then(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))');
    await writeFile(path.join(tmpdir(), 'moss-project-icon-edit.png'), (await window.webContents.capturePage()).toPNG());
    assert.equal(await evaluate("[...document.querySelectorAll('button')].some(b => b.textContent === '确认并创建')"), false);
    await evaluate("const input = document.querySelector('input'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, '修改后的项目'); input.dispatchEvent(new Event('input', { bubbles: true }));");
    await evaluate("document.querySelector('[aria-label=\"选择目录\"]').click()");
    await waitFor("document.body.textContent.includes('/tmp/project-fixture')");
    await evaluate("document.querySelector('[aria-label=\"选择用户研究\"]').click()");
    await evaluate("[...document.querySelectorAll('label')].find(l => l.textContent === '读取文档').querySelector('input').click()");
    await evaluate("document.querySelector('[data-project-resource-kind=\"app\"] button').click()");
    await waitFor("document.body.textContent.includes('市场新增资源')");
    await evaluate("[...document.querySelectorAll('button')].find(button => button.textContent.includes('市场新增资源')).click()");
    await click('确定');
    await click('保存并重新预览');
    await waitFor("document.body.textContent.includes('确认并创建')");
    const patch = JSON.parse(await evaluate("document.querySelector('[data-patch]').textContent"));
    assert.equal(patch.name, '修改后的项目'); assert.deepEqual(patch.skillIds, []);
    assert.deepEqual(patch.icon, { kind: 'generated', paths: originalPaths, color: 'blue' });
    assert.deepEqual(patch.appIds, ['docs', 'market-extra']);
    assert.deepEqual(patch.workspaces, ['/tmp/project-fixture']); assert.deepEqual(patch.appServiceIds, ['["docs","read"]']);
    await click('确认并创建');
    await waitFor("document.body.textContent.includes('配置 / 授权 App')");
    await click('配置 / 授权 App');
    await waitFor("document.querySelector('[data-action]').textContent === 'configure:docs'");
    await click('模拟安装失败');
    await waitFor("document.body.textContent.includes('下载失败')");
    await click('重试创建');
    await waitFor("document.body.textContent.includes('继续创建')");
    await click('取消方案');
    await waitFor("document.body.textContent.includes('方案已取消')");
    assert.equal(await evaluate("[...document.querySelectorAll('button')].some(b => ['确认并创建', '继续创建'].includes(b.textContent))"), false);
    console.log('PROJECT_CREATION_UI_PASSED: generated icon review, switching icons/colors, editing, directory, resources, authorization, retry and cancel');
  } catch (error) { console.error(error); process.exitCode = 1; }
  finally { clearTimeout(timeout); window?.destroy(); await server?.close(); await rm(temp, { recursive: true, force: true }); app.exit(process.exitCode || 0); }
});
