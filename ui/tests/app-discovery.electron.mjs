import { app, BrowserWindow } from 'electron'
import fs from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import assert from 'node:assert/strict'
import { createServer } from 'vite'
import { fileURLToPath } from 'node:url'
const root = fileURLToPath(new URL('..', import.meta.url))
const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'moss-discovery-ui-'))
const output = path.join(root, '../output/app-hub/discovery')
app.setPath('userData', path.join(temp, 'profile'))
const errors = []
let server, win
const delay = () => new Promise(resolve => setTimeout(resolve, 100))
const watchdog = setTimeout(() => app.exit(1), 60000)
app.whenReady().then(async () => {
try {
  server = await createServer({ root, configFile: path.join(root, 'vite.config.ts'), cacheDir: path.join(temp, 'vite'), server: { host: '127.0.0.1', port: 0, strictPort: false, hmr: false } })
  await server.listen()
  win = new BrowserWindow({ show: false, width: 1200, height: 850, useContentSize: true })
  win.webContents.on('console-message', (_event, level, text) => { if (level >= 3) errors.push(text) })
  const evaluate = (fn, ...args) => win.webContents.executeJavaScript(`(${fn})(${args.map(arg => JSON.stringify(arg)).join(',')})`)
  const until = async fn => { for (let i = 0; i < 150; i++) { if (await evaluate(fn)) return; await delay() } throw new Error('UI condition timed out: ' + fn) }
  const click = async (text, selector = 'button') => { assert(await evaluate((text, selector) => { const item = [...document.querySelectorAll(selector)].find(el => el.textContent.trim().startsWith(text)); item?.click(); return Boolean(item) }, text, selector), `missing ${text}`); await delay() }
  const titles = () => evaluate(() => [...document.querySelectorAll('section h3')].map(el => el.textContent))
  const capture = async name => { await fs.mkdir(output, { recursive: true }); await fs.writeFile(path.join(output, name + '.png'), (await win.webContents.capturePage()).toPNG()) }
  await win.loadURL(`http://127.0.0.1:${server.httpServer.address().port}/tests/fixtures/app-discovery.html`)
  await until(() => document.querySelectorAll('[data-app-market-open]').length === 7)
  assert.equal(await evaluate(() => document.querySelector('[data-app-hub-tab="marketplace"]').getAttribute('aria-selected')), 'true')
  assert((await titles()).includes('数据库') && (await titles()).includes('云客 CRM'), 'Apps and tools share the market list')
  assert.equal(await evaluate(() => document.querySelectorAll('[data-app-header] select').length), 0)
  assert.equal(await evaluate(() => [...document.querySelectorAll('[data-app-category]')].every(card => card.querySelectorAll('button').length === 1 && !card.querySelector('input,select'))), true)
  assert.doesNotMatch(await evaluate(() => [...document.querySelectorAll('[data-app-category]')].map(el => el.textContent).join(' ')), /已启用|已停用|已就绪|待连接|待授权|1\.0\.0|MCP|CLI skill/)
  await capture('market-all-light')
  await click('添加应用')
  assert.equal(await evaluate(() => window.__archiveImports), 1)
  await evaluate(() => document.querySelector('[data-app-hub-tab="installed"]').click())
  await until(() => document.querySelectorAll('[data-app-open]').length === 5)
  assert((await titles()).includes('数据库') && (await titles()).includes('腾讯地图'), 'Apps and tools share the installed list')
  assert.equal(await evaluate(() => document.querySelectorAll('[data-app-header] select').length), 0)
  await capture('installed-all-light')
  win.setContentSize(520, 850)
  await delay()
  assert(await evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'narrow installed list fits')
  await click('添加应用')
  assert.equal(await evaluate(() => window.__archiveImports), 2)
  await capture('installed-narrow')
  win.setContentSize(1200, 850)
  await evaluate(() => document.querySelector('[data-app-hub-tab="marketplace"]').click())
  await until(() => document.querySelectorAll('[data-app-market-open]').length === 7)
  await evaluate(() => document.querySelector('[data-app-market-open="moss.yunke-cli"]').click())
  await until(() => Boolean(document.querySelector('[data-app-market-details] select')))
  assert(await evaluate(() => document.querySelector('[data-app-market-details]').textContent.includes('KB')))
  await evaluate(() => {
    const select = document.querySelector('[aria-label="可用版本"]'); select.value = '0.9.0'; select.dispatchEvent(new Event('change', { bubbles: true }))
    window.confirm = () => false
  })
  await click('安装', '[data-app-market-details] header button')
  assert.equal(await evaluate(() => window.__marketInstalls.length), 1)
  assert.equal(await evaluate(() => window.__marketInstalls[0].version), '0.9.0')
  assert.equal(await evaluate(() => document.querySelector('[data-app-hub-tab="installed"]').textContent), '已安装 5')
  await evaluate(() => { window.confirm = () => true })
  await click('安装', '[data-app-market-details] header button')
  await until(() => document.querySelector('[data-app-market-details] header button').textContent === '已安装')
  assert.equal(await evaluate(() => window.__marketInstalls.at(-1).acceptPermissions), true)
  assert.equal(await evaluate(() => document.querySelector('[data-app-hub-tab="installed"]').textContent), '已安装 6')
  assert(await evaluate(() => document.querySelector('[data-app-market-details]').textContent.includes('已安装版本0.9.0')))
  await capture('installed-market-version')
  await evaluate(() => document.querySelector('[aria-label="市场详情导航"] button').click())
  await delay()
  assert.equal(await evaluate(() => document.querySelectorAll('[data-app-market-open]').length), 7)
  await evaluate(() => { document.documentElement.dataset.theme = 'dark' })
  await delay()
  assert.equal(await evaluate(() => getComputedStyle(document.body).colorScheme), 'dark')
  await capture('market-all-dark')
  win.setContentSize(520, 850)
  await delay()
  assert(await evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'narrow market fits')
  await capture('market-all-narrow')
  await win.loadURL(`http://127.0.0.1:${server.httpServer.address().port}/tests/fixtures/app-discovery.html?empty=1`)
  await until(() => document.querySelectorAll('[data-app-market-open]').length === 7)
  assert.equal(await evaluate(() => document.querySelector('[data-app-hub-tab="marketplace"]').getAttribute('aria-selected')), 'true')
  await evaluate(() => document.querySelector('[data-app-hub-tab="installed"]').click())
  await until(() => document.body.textContent.includes('暂无 App，请从应用市场安装'))
  assert.equal(await evaluate(() => document.querySelector('[data-app-hub-tab="installed"]').textContent), '已安装 0')
  await capture('empty-installed')
  await evaluate(() => document.querySelector('[data-app-hub-tab="marketplace"]').click())
  await until(() => document.querySelectorAll('[data-app-market-open]').length === 7)
  win.setContentSize(1200, 850)
  await win.loadURL(`http://127.0.0.1:${server.httpServer.address().port}/tests/fixtures/app-discovery.html?builtins=1`)
  await until(() => document.querySelectorAll('[data-app-market-open]').length === 7)
  await evaluate(() => document.querySelector('[data-app-hub-tab="installed"]').click())
  await click('内置应用')
  await until(() => document.querySelectorAll('[data-app-open]').length === 7)
  assert.equal(await evaluate(() => Boolean(document.querySelector('[data-app-open="moss.filesystem"]'))), false, 'builtins replace the list without duplicating installed Apps')
  assert.equal(await evaluate(() => [...document.querySelectorAll('[data-app-category]')].every(card => card.querySelectorAll('button').length === 1 && !card.querySelector('input,select'))), true)
  assert.doesNotMatch(await evaluate(() => [...document.querySelectorAll('[data-app-category]')].map(el => el.textContent).join(' ')), /已安装|未安装|恢复|0\.1\.0/)
  assert.equal(await evaluate(() => getComputedStyle(document.querySelector('[data-app-category]').parentElement).gridTemplateColumns.split(' ').length), 3)
  await capture('builtin-three-columns')
  await evaluate(() => document.querySelector('[data-app-open="moss.visualize"]').click())
  assert.deepEqual(await evaluate(() => window.__opened), ['moss.visualize'], 'installed builtin uses the normal App detail route')
  await evaluate(() => {
    const input = document.querySelector('[aria-label="搜索应用"]')
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, 'PDF')
    input.dispatchEvent(new Event('input', { bubbles: true }))
  })
  await until(() => document.querySelectorAll('[data-app-open]').length === 1)
  await evaluate(() => document.querySelector('[data-app-open="moss.pdf"]').click())
  await until(() => Boolean(document.querySelector('[data-app-builtin-details]')))
  await click('恢复应用', '[data-app-builtin-details] header button')
  await until(() => document.querySelector('[data-app-builtin-details] [role="alert"]')?.textContent === '测试恢复失败')
  await evaluate(() => { window.__restores.mode = 'pending' })
  await click('恢复应用', '[data-app-builtin-details] header button')
  assert.equal(await evaluate(() => document.querySelector('[data-app-builtin-details] header button').disabled), true)
  await click('恢复中', '[data-app-builtin-details] header button')
  assert.equal(await evaluate(() => window.__restores.calls.length), 2, 'restore is not submitted twice')
  await evaluate(() => window.__restores.finish())
  await until(() => document.querySelector('[data-app-builtin-details] header button')?.textContent === '查看详情')
  assert.equal(await evaluate(() => document.querySelector('[data-app-builtin-details] [role="alert"]')), null)
  assert.equal(await evaluate(() => document.querySelector('[data-app-hub-tab="installed"]').textContent), '已安装 8')
  await capture('builtin-restored-details')
  await click('查看详情', '[data-app-builtin-details] header button')
  assert.equal(await evaluate(() => window.__opened.at(-1)), 'moss.pdf')
  await evaluate(() => document.querySelector('[aria-label="内置应用详情导航"] button').click())
  await until(() => !document.querySelector('[data-app-builtin-details]'))
  assert.equal(await evaluate(() => document.querySelector('[aria-label="搜索应用"]').value), 'PDF', 'return preserves search')
  await evaluate(() => document.querySelector('[data-app-open="moss.pdf"]').click())
  assert.equal(await evaluate(() => window.__opened.at(-1)), 'moss.pdf', 'restored card now opens installed details')
  await click('内置应用')
  await evaluate(() => {
    const input = document.querySelector('[aria-label="搜索应用"]')
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, '')
    input.dispatchEvent(new Event('input', { bubbles: true }))
  })
  await until(() => document.querySelectorAll('[data-app-open]').length === 8)
  assert.deepEqual(errors, [])
  await fs.writeFile(path.join(output, 'verification.json'), JSON.stringify({ ok: true, checks: ['market-default', 'market-installed-tabs', 'display-only-cards', 'apps-and-tools-together', 'version-selection', 'permission-cancel-and-confirm', 'archive-import', 'empty-installed', 'light-dark-narrow', 'builtin-three-columns', 'builtin-restore-error-and-retry', 'builtin-open-installed-details'], errors }, null, 2))
  console.log('App discovery UI checks passed')
} catch (error) { console.error(error); process.exitCode = 1 }
finally { clearTimeout(watchdog); win?.destroy(); await server?.close(); await fs.rm(temp, { recursive: true, force: true }); app.exit(process.exitCode || 0) }

})
